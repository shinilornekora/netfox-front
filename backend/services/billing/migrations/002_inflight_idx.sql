-- Найдено нагрузочным замером (docs/evidence/01-workload.md).
--
-- Проверка «нет ли у зрителя заказа в работе» (шаг prepare, SERIALIZABLE)
-- шла по частичному индексу orders_stuck_idx (ключ — updated_at, условие
-- status IN ('charging','refunding')): условие запроса совпадало с условием
-- индекса, и обобщённый план подготовленного запроса выбирал именно его,
-- фильтруя user_id уже после чтения. Получалось чтение ВСЕГО индекса, то есть
-- предикатная блокировка на весь индекс, а каждая новая покупка вставляет
-- туда свой заказ в статусе charging. Итог: покупки РАЗНЫХ зрителей
-- конфликтовали друг с другом (ложные конфликты SSI) и после шести попыток
-- заканчивались ошибкой — около 1% покупок при 8 параллельных.
--
-- 1) Индекс с ведущим user_id — проверка читает только страницы одного зрителя.
CREATE INDEX orders_user_status_idx ON orders (user_id, status);
-- 2) Индекс для восстановителя делаем полным (status, updated_at): он
--    по-прежнему находит зависшие заказы, но больше не «подходит» под
--    проверку зрителя лучше, чем индекс по user_id.
DROP INDEX orders_stuck_idx;
CREATE INDEX orders_stuck_idx ON orders (status, updated_at);
