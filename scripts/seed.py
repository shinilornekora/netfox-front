def poster(c, title_id, slug):
    path = os.path.join(HERE, "posters", slug + ".jpg")
    if not os.path.exists(path):
        return
    with open(path, "rb") as f:
        st, js = c.call("PUT", f"/api/admin/titles/{title_id}/poster", data=f.read())
    if st != 200:
        raise AssertionError(f"poster {slug}: {st} {js}")
    return js


def main(base, email, pw):
    c = Client(base)
    c.ok("POST", "/api/auth/login", {"email": email, "password": pw})
    existing = {t["name"] for t in c.ok("GET", "/api/admin/titles?limit=100")["items"]}
    made = 0
    for slug, name, orig, year, age, genres, minutes, sub, price, hue, desc in FILMS:
        if name in existing:
            continue
        t = c.ok("POST", "/api/admin/titles", {"kind": "film", "name": name, "original_name": orig, "year": year,
                 "age_rating": age, "genres": genres, "duration_sec": minutes * MIN, "in_subscription": sub,
                 "price_kopecks": price * 100, "poster_hue": hue, "description": desc,
                 "media": slug + ".mp4"})
        t = poster(c, t["id"], slug) or t
        c.ok("POST", f"/api/admin/titles/{t['id']}/publish", {"revision": t["revision"]})
        made += 1
    for slug, name, orig, year, age, genres, hue, desc, eps in SERIES:
        if name in existing:
            continue
        t = c.ok("POST", "/api/admin/titles", {"kind": "series", "name": name, "original_name": orig, "year": year,
                 "age_rating": age, "genres": genres, "in_subscription": True, "poster_hue": hue, "description": desc})
        for n, (ep, minutes) in enumerate(eps, 1):
            c.ok("PUT", f"/api/admin/titles/{t['id']}/episodes",
                 {"season": 1, "number": n, "name": ep, "duration_sec": minutes * MIN,
                  "media": f"{slug}-{n:02d}.mp4"})
        poster(c, t["id"], slug)
        t = c.ok("GET", f"/api/titles/{t['id']}")
        c.ok("POST", f"/api/admin/titles/{t['id']}/publish", {"revision": t["revision"]})
        made += 1
    print(f"seeded {made} titles")


if __name__ == "__main__":
    main(*(sys.argv[1:4] if len(sys.argv) >= 4 else ("http://localhost:8080", "admin@plenka.local", "admin12345")))
